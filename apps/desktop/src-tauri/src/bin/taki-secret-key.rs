//! INPUT:  argv — `get --account <name>` | `create --account <name>` | `credential --name <file>`;
//!         `create` additionally reads a u32-LE-length-prefixed key from stdin; env — CREDENTIALS_DIRECTORY for
//!         the `credential` subcommand (systemd `LoadCredentialEncrypted=` exposes the decrypted file there)
//! OUTPUT: the catalog master-key helper for the Core process: `get`/`create` use Windows Credential Manager via
//!         the shipped KeyringStore (service "TakiAgent", versioned account names like
//!         `secret-catalog-master-key-v1`); `credential` streams the systemd-delivered key file; key bytes leave
//!         ONLY as `[u32 LE length][bytes]` on stdout for the calling process, diagnostics go to stderr and never
//!         contain key material; `create` is create-only (an existing account is refused, never overwritten)
//! POS:    shell/bin — release-safe (unlike taki-node it grants nothing: no approver, no capability); account
//!         model is the frozen interactive-user rule — Core and this helper must run as the same logged-in user,
//!         because Credential Manager entries bind to the current token's logon session

use std::io::{Read, Write};
use std::path::PathBuf;

use taki_desktop_lib::secrets::{KeyringStore, SecretStore};

/// libsodium `crypto_secretstream_xchacha20poly1305_KEYBYTES`.
const KEY_BYTES: usize = 32;
const EXIT_OK: i32 = 0;
const EXIT_USAGE: i32 = 2;
const EXIT_MISSING: i32 = 3;
const EXIT_EXISTS: i32 = 4;
const EXIT_STORE: i32 = 5;

struct Outcome {
    code: i32,
    stdout: Vec<u8>,
    stderr: String,
}

impl Outcome {
    fn ok_key(key: &[u8]) -> Self {
        Self { code: EXIT_OK, stdout: frame(key), stderr: String::new() }
    }

    fn fail(code: i32, message: &str) -> Self {
        Self { code, stdout: Vec::new(), stderr: format!("taki-secret-key: {message}\n") }
    }
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let stdin = read_all(std::io::stdin().lock());
    let outcome = dispatch(&args, &stdin, std::env::var_os("CREDENTIALS_DIRECTORY").map(PathBuf::from), &KeyringStore::new());
    if !outcome.stderr.is_empty() {
        eprint!("{}", outcome.stderr);
    }
    if !outcome.stdout.is_empty() && std::io::stdout().write_all(&outcome.stdout).is_err() {
        std::process::exit(EXIT_STORE);
    }
    std::process::exit(outcome.code);
}

fn dispatch(args: &[String], stdin: &[u8], credentials_dir: Option<PathBuf>, store: &dyn SecretStore) -> Outcome {
    match args.first().map(String::as_str) {
        Some("get") => match named(args, "--account") {
            Some(account) => cmd_get(store, account),
            None => Outcome::fail(EXIT_USAGE, "usage: get --account <name>"),
        },
        Some("create") => match named(args, "--account") {
            Some(account) => cmd_create(store, account, stdin),
            None => Outcome::fail(EXIT_USAGE, "usage: create --account <name> (key arrives framed on stdin)"),
        },
        Some("credential") => match named(args, "--name") {
            Some(name) => cmd_credential(credentials_dir, name),
            None => Outcome::fail(EXIT_USAGE, "usage: credential --name <file>"),
        },
        _ => Outcome::fail(
            EXIT_USAGE,
            "usage: taki-secret-key get|create|credential (see the module header for flags)",
        ),
    }
}

fn cmd_get(store: &dyn SecretStore, account: &str) -> Outcome {
    match store.get(account) {
        Ok(Some(stored)) => match hex_decode(&stored) {
            Some(key) if key.len() == KEY_BYTES => Outcome::ok_key(&key),
            _ => Outcome::fail(EXIT_STORE, "stored credential has the wrong length or encoding"),
        },
        Ok(None) => Outcome::fail(EXIT_MISSING, "credential missing"),
        Err(error) => Outcome::fail(EXIT_STORE, &format!("credential store error: {error}")),
    }
}

// Create-only: the key material itself is generated by the CALLING process (Core, via libsodium keygen) — this
// helper adds no randomness source and never overwrites an existing entry.
fn cmd_create(store: &dyn SecretStore, account: &str, stdin: &[u8]) -> Outcome {
    let Some(key) = parse_frame(stdin) else {
        return Outcome::fail(EXIT_USAGE, "stdin must carry exactly one length-prefixed key");
    };
    if key.len() != KEY_BYTES {
        return Outcome::fail(EXIT_USAGE, "key must be 32 bytes");
    }
    match store.get(account) {
        Ok(Some(_)) => Outcome::fail(EXIT_EXISTS, "credential exists; create never overwrites"),
        Ok(None) => match store.set(account, &hex_encode(&key)) {
            Ok(()) => Outcome { code: EXIT_OK, stdout: Vec::new(), stderr: String::new() },
            Err(error) => Outcome::fail(EXIT_STORE, &format!("credential store error: {error}")),
        },
        Err(error) => Outcome::fail(EXIT_STORE, &format!("credential store error: {error}")),
    }
}

// The Linux/VPS path: the master key arrives via systemd `LoadCredentialEncrypted=` as a file under
// $CREDENTIALS_DIRECTORY. Absence or a wrong-size file fails closed — no fallback, no prompt.
fn cmd_credential(credentials_dir: Option<PathBuf>, name: &str) -> Outcome {
    let Some(dir) = credentials_dir else {
        return Outcome::fail(EXIT_MISSING, "CREDENTIALS_DIRECTORY is not set");
    };
    let bytes = match std::fs::read(dir.join(name)) {
        Ok(bytes) => bytes,
        Err(_) => return Outcome::fail(EXIT_MISSING, "credential file missing"),
    };
    if bytes.len() != KEY_BYTES {
        return Outcome::fail(EXIT_MISSING, "credential file must be exactly 32 bytes");
    }
    Outcome::ok_key(&bytes)
}

/// The first value following `--<flag>` (flag then value); `None` when the flag is absent or valueless.
fn named<'a>(args: &'a [String], flag: &str) -> Option<&'a str> {
    let index = args.iter().position(|arg| arg == flag)?;
    args.get(index + 1).map(String::as_str).filter(|value| !value.is_empty())
}

fn read_all(mut reader: impl Read) -> Vec<u8> {
    let mut buffer = Vec::new();
    let _ = reader.read_to_end(&mut buffer);
    buffer
}

/// `[u32 LE length][bytes]` — the stdout contract with the calling Core process.
fn frame(key: &[u8]) -> Vec<u8> {
    let mut framed = (key.len() as u32).to_le_bytes().to_vec();
    framed.extend_from_slice(key);
    framed
}

/// Accepts exactly one framed buffer and nothing more; `None` on any framing deviation.
fn parse_frame(bytes: &[u8]) -> Option<Vec<u8>> {
    if bytes.len() < 4 {
        return None;
    }
    let length = u32::from_le_bytes([bytes[0], bytes[1], bytes[2], bytes[3]]) as usize;
    let key = bytes.get(4..)?;
    if key.len() != length {
        return None;
    }
    Some(key.to_vec())
}

fn hex_encode(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

fn hex_decode(text: &str) -> Option<Vec<u8>> {
    if !text.len().is_multiple_of(2) || !text.bytes().all(|b| b.is_ascii_hexdigit()) {
        return None;
    }
    (0..text.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(text.get(i..i + 2)?, 16).ok())
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;
    use std::sync::Mutex;

    /// Hermetic fake — never touches Credential Manager (machine-global state, ruling 5).
    struct FakeStore {
        map: Mutex<HashMap<String, String>>,
    }

    impl FakeStore {
        fn new() -> Self {
            Self { map: Mutex::new(HashMap::new()) }
        }
    }

    impl SecretStore for FakeStore {
        fn get(&self, key: &str) -> Result<Option<String>, String> {
            Ok(self.map.lock().unwrap().get(key).cloned())
        }

        fn set(&self, key: &str, secret: &str) -> Result<(), String> {
            self.map.lock().unwrap().insert(key.to_string(), secret.to_string());
            Ok(())
        }

        fn delete(&self, key: &str) -> Result<(), String> {
            self.map.lock().unwrap().remove(key);
            Ok(())
        }
    }

    const KEY: [u8; KEY_BYTES] = [0x5a; KEY_BYTES];

    fn framed_key() -> Vec<u8> {
        frame(&KEY)
    }

    #[test]
    fn get_returns_the_framed_key_and_missing_fails_closed() {
        let store = FakeStore::new();
        let account = "secret-catalog-master-key-v1";
        let missing = dispatch(&["get".into(), "--account".into(), account.into()], &[], None, &store);
        assert_eq!(missing.code, EXIT_MISSING);
        assert!(missing.stdout.is_empty());

        store.set(account, &hex_encode(&KEY)).unwrap();
        let found = dispatch(&["get".into(), "--account".into(), account.into()], &[], None, &store);
        assert_eq!(found.code, EXIT_OK);
        assert_eq!(found.stdout, framed_key());
        assert!(found.stderr.is_empty());
    }

    #[test]
    fn create_is_create_only_and_never_overwrites() {
        let store = FakeStore::new();
        let account = "secret-catalog-master-key-v1";
        let created = dispatch(
            &["create".into(), "--account".into(), account.into()],
            &framed_key(),
            None,
            &store,
        );
        assert_eq!(created.code, EXIT_OK);
        assert_eq!(store.get(account).unwrap().as_deref(), Some(hex_encode(&KEY).as_str()));

        let mut other = [0x11u8; KEY_BYTES];
        other[0] = 0x22;
        let again = dispatch(
            &["create".into(), "--account".into(), account.into()],
            &frame(&other),
            None,
            &store,
        );
        assert_eq!(again.code, EXIT_EXISTS);
        // The stored key is the ORIGINAL — the second create changed nothing.
        assert_eq!(store.get(account).unwrap().as_deref(), Some(hex_encode(&KEY).as_str()));
    }

    #[test]
    fn create_rejects_unframed_and_wrong_length_stdin() {
        let store = FakeStore::new();
        let args = ["create".into(), "--account".into(), "a".into()];
        assert_eq!(dispatch(&args, b"raw-bytes-no-frame", None, &store).code, EXIT_USAGE);
        let short = frame(&[0u8; 16]);
        assert_eq!(dispatch(&args, &short, None, &store).code, EXIT_USAGE);
        let trailing = [framed_key(), b"x".to_vec()].concat();
        assert_eq!(dispatch(&args, &trailing, None, &store).code, EXIT_USAGE);
    }

    #[test]
    fn credential_reads_credentials_directory_and_fails_closed() {
        let dir = tempfile::tempdir().unwrap();
        let name = "taki-secret-catalog-master-key";

        let absent_dir = dispatch(
            &["credential".into(), "--name".into(), name.into()],
            &[],
            None,
            &FakeStore::new(),
        );
        assert_eq!(absent_dir.code, EXIT_MISSING);

        let missing_file = dispatch(
            &["credential".into(), "--name".into(), name.into()],
            &[],
            Some(dir.path().to_path_buf()),
            &FakeStore::new(),
        );
        assert_eq!(missing_file.code, EXIT_MISSING);

        std::fs::write(dir.path().join(name), [0u8; 8]).unwrap();
        let wrong_size = dispatch(
            &["credential".into(), "--name".into(), name.into()],
            &[],
            Some(dir.path().to_path_buf()),
            &FakeStore::new(),
        );
        assert_eq!(wrong_size.code, EXIT_MISSING);

        std::fs::write(dir.path().join(name), KEY).unwrap();
        let ok = dispatch(
            &["credential".into(), "--name".into(), name.into()],
            &[],
            Some(dir.path().to_path_buf()),
            &FakeStore::new(),
        );
        assert_eq!(ok.code, EXIT_OK);
        assert_eq!(ok.stdout, framed_key());
    }

    #[test]
    fn usage_complaints_are_bounded_and_value_free() {
        let store = FakeStore::new();
        assert_eq!(dispatch(&[], &[], None, &store).code, EXIT_USAGE);
        assert_eq!(dispatch(&["get".into()], &[], None, &store).code, EXIT_USAGE);
        assert!(!dispatch(&["frobnicate".into()], &[], None, &store).stderr.is_empty());
    }

    #[test]
    fn hex_roundtrips_and_rejects_odd_or_non_hex() {
        assert_eq!(hex_decode(&hex_encode(&KEY)).unwrap(), KEY.to_vec());
        assert_eq!(hex_encode(&[0x00, 0xff]), "00ff");
        assert!(hex_decode("abc").is_none());
        assert!(hex_decode("zz").is_none());
    }
}
