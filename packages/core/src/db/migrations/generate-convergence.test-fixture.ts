/**
 * INPUT: immutable historical migrations and isolated in-memory creation SQL
 * OUTPUT: reproducible static schema constants for guarded main/T4 convergence
 * POS: core/db/migrations — development fixture generator; never imported at Core startup
 */
import { writeFileSync } from "node:fs";
import { openDatabase } from "../sqlite.ts";
import { MAIN_HISTORICAL_MIGRATIONS } from "./historical-main.ts";
import { T4_HISTORICAL_MIGRATIONS } from "./historical-t4.ts";
import { INITIATIVE_MISSING_SQL, DELEGATION_MISSING_SQL, OBSERVATION_MISSING_SQL, MODEL_MISSING_SQL, MAIN_MISSING_SQL } from "./convergence-sql.ts";

interface ObjectRow { type: string; name: string; tbl_name: string; sql: string }
const read = (db: ReturnType<typeof openDatabase>) => db.prepare(
  "SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE sql IS NOT NULL ORDER BY name").all() as unknown as ObjectRow[];
const snapshot = (migrations: typeof MAIN_HISTORICAL_MIGRATIONS) => {
  const db = openDatabase({ path: ":memory:", migrations }); const rows = read(db); db.close(); return rows;
};
const common = snapshot(MAIN_HISTORICAL_MIGRATIONS.filter(({ version }) => version <= 48));
const main = snapshot(MAIN_HISTORICAL_MIGRATIONS);
const t4 = snapshot(T4_HISTORICAL_MIGRATIONS);
const t4WithoutModels = snapshot(T4_HISTORICAL_MIGRATIONS.filter(({ version }) => version <= 68));
const unionDb = openDatabase({ path: ":memory:", migrations: T4_HISTORICAL_MIGRATIONS });
unionDb.transaction(() => unionDb.exec(MAIN_MISSING_SQL));
const union = read(unionDb); unionDb.close();
const db = openDatabase({ path: ":memory:", migrations: MAIN_HISTORICAL_MIGRATIONS });
const groups = [INITIATIVE_MISSING_SQL, DELEGATION_MISSING_SQL, OBSERVATION_MISSING_SQL, MODEL_MISSING_SQL];
const stages: ObjectRow[][] = [read(db)];
for (const sql of groups) { db.transaction(() => db.exec(sql)); stages.push(read(db)); }
db.close();
const changed = (before: ObjectRow[], after: ObjectRow[]) => {
  const old = new Map(before.map((row) => [row.name, row.sql]));
  return after.filter((row) => old.get(row.name) !== row.sql).map((row) => row.name);
};
const domains = groups.map((_, index) => changed(stages[index]!, stages[index + 1]!));
const snapshots = { COMMON_SCHEMA: common, MAIN_SCHEMA: main, T4_SCHEMA: t4,
  T4_WITHOUT_MODELS_SCHEMA: t4WithoutModels, UNION_SCHEMA: union,
  INITIATIVE_STAGE_SCHEMA: stages[1]!, DELEGATION_STAGE_SCHEMA: stages[2]!, OBSERVATION_STAGE_SCHEMA: stages[3]! };
const header = `/**
 * INPUT: isolated execution of immutable main063/T4072 migration definitions
 * OUTPUT: frozen exact schema signatures for recognized convergence inputs
 * POS: core/db/migrations — generated by generate-convergence.test-fixture.ts; do not edit by hand
 */
import type { MigrationSchemaObject } from "../migration-runner.ts";
interface FrozenSchemaObject extends MigrationSchemaObject { table: string }
`;
const objects = new Map<string, number>();
const entries: Array<{ type: string; name: string; table: string; sql: string }> = [];
const arrays = Object.entries(snapshots).map(([name, rows]) => {
  const indices = rows.map(({ type, name: objectName, tbl_name: table, sql }) => {
    const key = JSON.stringify([type, objectName, table, sql]);
    if (!objects.has(key)) { objects.set(key, entries.length); entries.push({ type, name: objectName, table, sql }); }
    return objects.get(key)!;
  });
  return `export const ${name}: readonly FrozenSchemaObject[] = ${JSON.stringify(indices)}.map((index) => OBJECTS[index]!);`;
}).join("\n\n");
const objectText = `const OBJECTS: readonly FrozenSchemaObject[] = ${JSON.stringify(entries, null, 2)};`;
const domainText = domains.map((names, index) => `export const GROUP_${index + 74}_OBJECT_NAMES: readonly string[] = ${JSON.stringify(names, null, 2)};`).join("\n\n");
writeFileSync(new URL("./073-convergence-schema.generated.ts", import.meta.url), `${header}\n${objectText}\n\n${arrays}\n\n${domainText}\n`);
console.log(JSON.stringify({ common: common.length, main: main.length, t4: t4.length, union: union.length, domains: domains.map((names) => names.length) }));
