/**
 * INPUT: selected browser/player observations forwarded by a paired Shell
 * OUTPUT: strict observation/report/read contracts; no credentials, consent or model instructions
 * POS: shared/protocol — Node report shapes are mirrored by Shell serde; Core owns source references
 */
import { z } from "zod";

export const BROWSER_PLAYBACK_METHODS = { ready: "browser.playback.ready", report: "browser.playback.report",
  read: "browser.playback.read", control: "browser.playback.control" } as const;
export const BROWSER_PLAYBACK_ENABLED_KEY = "TAKI_BROWSER_PLAYBACK_ENABLED";
export const BROWSER_PLAYBACK_FRESH_MS = 5_000;
export const BROWSER_PLAYBACK_MAX_SOURCES = 64;

export const BrowserMediaIdentitySchema = z.strictObject({
  kind: z.literal("bilibili"), bvid: z.string().regex(/^BV[0-9A-Za-z]{10}$/),
  cid: z.string().regex(/^[1-9][0-9]{0,19}$/), page: z.int().positive(),
});
// Chromium reports its document identity as an opaque 32-hex token. Preserve those bytes;
// it is not the RFC UUID generated by this extension for the physical player element.
export const BrowserDocumentIdSchema = z.union([z.string().regex(/^[0-9a-fA-F]{32}$/), z.uuid()]);
export const BrowserPlayerIdentitySchema = z.strictObject({
  tabId: z.int().nonnegative(), frameId: z.int().nonnegative(), documentId: BrowserDocumentIdSchema, playerId: z.uuid(),
  media: BrowserMediaIdentitySchema,
});
export const BrowserPlaybackSampleSchema = z.strictObject({
  state: z.enum(["playing", "paused", "buffering", "seeking", "ended"]),
  positionSeconds: z.number().nonnegative().nullable(), durationSeconds: z.number().nonnegative().nullable(),
  playbackRate: z.number().positive().nullable(), visible: z.boolean(), pictureInPicture: z.boolean(),
}).refine((value) => value.positionSeconds === null || value.durationSeconds === null
  || value.positionSeconds <= value.durationSeconds, { message: "Position exceeds observed duration" });

const reportBinding = {
  schemaVersion: z.literal("taki.browser-playback.v1"), catalogGeneration: z.int().positive(),
  attachmentId: z.uuid(), attachmentGeneration: z.int().positive(), sequence: z.int().positive(),
};
export const BrowserPlaybackReportSchema = z.discriminatedUnion("kind", [
  z.strictObject({ ...reportBinding, kind: z.literal("sample"), source: BrowserPlayerIdentitySchema,
    sample: BrowserPlaybackSampleSchema, observedAgeMs: z.number().nonnegative().max(30_000) }),
  z.strictObject({ ...reportBinding, kind: z.literal("retired") }),
]);
// The local extension channel omits Core/Shell authority and attachment generations. The Shell adds those facts.
export const BrowserAttachmentHelloSchema = z.strictObject({
  kind: z.literal("hello"), protocol: z.literal("taki.browser-attachment.v1"), token: z.string().regex(/^[0-9a-f]{64}$/),
});
export const BrowserAttachmentPairSchema = z.strictObject({
  endpoint: z.string().regex(/^ws:\/\/127\.0\.0\.1:[0-9]{4,5}\/taki-browser$/), token: z.string().regex(/^[0-9a-f]{64}$/),
});
export const BrowserAttachmentSetupResultSchema = z.strictObject({ restartRequired: z.boolean() });
export const BrowserAttachmentFrameSchema = z.discriminatedUnion("kind", [
  z.strictObject({ kind: z.literal("sample"), sequence: z.int().positive(), source: BrowserPlayerIdentitySchema,
    sample: BrowserPlaybackSampleSchema, observedAgeMs: z.number().nonnegative().max(30_000) }),
  z.strictObject({ kind: z.literal("retired"), sequence: z.int().positive() }),
]);
export const BrowserPlaybackAckSchema = z.discriminatedUnion("accepted", [
  z.strictObject({ accepted: z.literal(true) }),
  z.strictObject({ accepted: z.literal(false), reason: z.enum([
    "disabled", "invalid_report", "wrong_host", "stale_generation", "stale_source", "duplicate", "capacity",
  ]) }),
]);
export const BrowserPlaybackViewSchema = z.strictObject({
  sourceRef: z.uuid(), hostId: z.uuid(), connectionGeneration: z.int().positive(), catalogGeneration: z.int().positive(),
  attachmentId: z.uuid(), attachmentGeneration: z.int().positive(), sequence: z.int().positive(),
  source: BrowserPlayerIdentitySchema, sample: BrowserPlaybackSampleSchema,
  receivedAt: z.iso.datetime(), freshUntil: z.iso.datetime(),
});
export const BrowserPlaybackReadParamsSchema = z.strictObject({});
export const BrowserPlaybackReadyParamsSchema = z.strictObject({ schemaVersion: z.literal("taki.browser-playback.v1") });
export const BrowserPlaybackControlSchema = z.strictObject({
  schemaVersion: z.literal("taki.browser-playback-control.v1"), hostId: z.uuid(), connectionGeneration: z.int().positive(),
  catalogGeneration: z.int().positive(), revision: z.int().positive(), enabled: z.boolean(),
});
export const BrowserPlaybackReadResultSchema = z.strictObject({
  enabled: z.boolean(), sources: z.array(BrowserPlaybackViewSchema).max(BROWSER_PLAYBACK_MAX_SOURCES),
});
export type BrowserMediaIdentity = z.infer<typeof BrowserMediaIdentitySchema>;
export type BrowserPlayerIdentity = z.infer<typeof BrowserPlayerIdentitySchema>;
export type BrowserPlaybackSample = z.infer<typeof BrowserPlaybackSampleSchema>;
export type BrowserPlaybackReport = z.infer<typeof BrowserPlaybackReportSchema>;
export type BrowserPlaybackAck = z.infer<typeof BrowserPlaybackAckSchema>;
export type BrowserPlaybackView = z.infer<typeof BrowserPlaybackViewSchema>;
export type BrowserPlaybackReadResult = z.infer<typeof BrowserPlaybackReadResultSchema>;
export type BrowserPlaybackControl = z.infer<typeof BrowserPlaybackControlSchema>;
export type BrowserAttachmentPair = z.infer<typeof BrowserAttachmentPairSchema>;
